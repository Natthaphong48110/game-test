// ระบบฐานความรู้อัจฉริยะสำหรับพี่โรโบ เมื่อรันบน GitHub Pages (Static Hosting) หรือออฟไลน์
export function getLocalRoboAnswer(question: string): string {
  const q = question.toLowerCase();

  if (q.includes('อัลกอริทึม') || q.includes('คืออะไร') || q.includes('algorithm')) {
    return '🤖 อัลกอริทึม (Algorithm) คือ "ลำดับขั้นตอนที่ชัดเจน" ในการทำงานหรือแก้ปัญหาครับ!\n\nเช่น การแปรงฟัน:\n1. หยิบแปรงและบีบยาสีฟัน\n2. แปรงฟันให้ทั่ว\n3. บ้วนปากด้วยน้ำสะอาด\n\nถ้าเราทำสลับขั้นตอน เช่น บ้วนปากก่อนแปรง ฟันก็จะไม่สะอาด ลำดับขั้นตอนที่ถูกต้องนี่แหละคือหัวใจของอัลกอริทึมครับ! ✨';
  }

  if (q.includes('ทำไมต้องทำตามขั้นตอน') || q.includes('ลำดับ') || q.includes('ขั้นตอน')) {
    return '🤖 เพราะคอมพิวเตอร์และหุ่นยนต์ไม่สามารถเดาใจเราได้ครับ! มันจะทำตามคำสั่งเป๊ะๆ ทีละบรรทัด\n\nถ้าเราสั่งสลับลำดับ เช่น สั่งให้ "ใส่รองเท้า" ก่อน "ใส่ถุงเท้า" หุ่นยนต์ก็จะงงและทำงานผิดพลาดทันทีเลยครับ!';
  }

  if (q.includes('ชีวิตประจำวัน') || q.includes('ตัวอย่าง')) {
    return '🤖 ในชีวิตประจำวันเราใช้อัลกอริทึมตลอดเวลาเลยนะ เช่น:\n🍳 การทอดไข่เจียว (ตอกไข่ -> ตีไข่ -> ตั้งกระทะ -> เทไข่)\n🎒 การจัดกระเป๋านักเรียนตามตารางสอน\n🌱 การปลูกต้นถั่วเขียว (เตรียมดิน -> หยอดเมล็ด -> รดน้ำ -> รับแสงแดด)\n\nการคิดเป็นขั้นตอนจะช่วยให้งานสำเร็จง่ายขึ้นเยอะเลยครับ!';
  }

  if (q.includes('loop') || q.includes('ลูป') || q.includes('ทำซ้ำ')) {
    return '🔄 Loop (การทำซ้ำ) เจ๋งมากๆ ครับ! แทนที่เราจะสั่งหุ่นยนต์ว่า "ก้าวหน้า ก้าวหน้า ก้าวหน้า ก้าวหน้า" ถึง 4 ครั้ง\n\nเราแค่สั่งว่า "ทำซ้ำ 4 รอบ: เดินหน้า" แค่นี้โค้ดก็สั้นลง และหุ่นยนต์ก็ทำงานได้เร็วขึ้น ไม่เหนื่อยด้วยครับ!';
  }

  if (q.includes('บั๊ก') || q.includes('bug') || q.includes('debug') || q.includes('แก้')) {
    return '🐛 บั๊ก (Bug) คือ "จุดผิดพลาด" ในคำสั่งหรือโปรแกรม เช่น สั่งให้โรโบเลี้ยวผิดทางจนชนกำแพง\n\nส่วน ดีบั๊ก (Debug) คือการสวมบทนักสืบไปหาว่าผิดที่ขั้นตอนไหน แล้วแก้ไขให้ถูกต้อง คนเก่งทุกคนต้องเคยเจอบั๊กทั้งนั้น อย่ากลัวที่จะลองใหม่นะ!';
  }

  if (q.includes('แตกย่อย') || q.includes('decomposition') || q.includes('แยก')) {
    return '🧩 การแยกย่อยปัญหา (Decomposition) คือการหั่นงานชิ้นใหญ่ๆ ให้เป็นชิ้นเล็กๆ ครับ\n\nเช่น ถ้าอยาก "ทำความสะอาดบ้าน" ฟังดูเหนื่อยมาก! แต่ถ้าเราแบ่งเป็น:\n1. กวาดห้องนอน\n2. ล้างจาน\n3. ทิ้งขยะ\nจะเห็นว่าเราทำทีละอย่างได้ง่ายขึ้นเยอะเลยครับ!';
  }

  if (q.includes('รูปแบบ') || q.includes('pattern') || q.includes('แพทเทิร์น')) {
    return '🔍 การจดจำรูปแบบ (Pattern Recognition) คือการมองหาสิ่งที่เกิดขึ้นซ้ำๆ หรือความเหมือนกันครับ\n\nเช่น สังเกตว่าเพลงท่อนฮุกร้องซ้ำเดิม หรือสัญญาณไฟจราจรเปลี่ยน แดง-เขียว-เหลือง วนไปเรื่อยๆ เมื่อเราเห็นแพทเทิร์น เราจะเดาผลลัพธ์ล่วงหน้าได้เก่งขึ้น!';
  }

  if (q.includes('นามธรรม') || q.includes('abstraction') || q.includes('สำคัญ')) {
    return '🎯 การคิดเชิงนามธรรม (Abstraction) คือการ "เลือกดูเฉพาะสิ่งที่สำคัญ" แล้วตัดสิ่งที่ไม่จำเป็นทิ้งไปครับ\n\nเช่น แผนที่รถไฟ จะวาดแค่สถานีและเส้นทาง ไม่ต้องวาดต้นไม้หรือเสาไฟฟ้า เพราะเราอยากรู้แค่ว่าต้องนั่งไปลงสถานีไหนนั่นเอง!';
  }

  if (q.includes('จัดเรียง') || q.includes('sort') || q.includes('เรียงลำดับ')) {
    return '📊 การจัดเรียง (Sorting Algorithm) คือการนำข้อมูลมาเรียงตามลำดับ เช่น เรียงจากน้อยไปมาก หรือเรียงแถวนักเรียนจากเตี้ยไปสูง\n\nเมื่อสิ่งของถูกจัดเรียงเป็นระเบียบ เราจะค้นหาสิ่งที่ต้องการได้รวดเร็วขึ้นเยอะเลยครับ!';
  }

  if (q.includes('หุ่นยนต์') || q.includes('โรโบ') || q.includes('เดินยังไง') || q.includes('เล่นยังไง')) {
    return '🤖 ในเกมพาน้องโรโบเดิน น้องๆ สามารถกดเลือกบล็อกคำสั่ง (เดินหน้า, หันซ้าย, หันขวา, กระโดดข้าม) แล้วกดปุ่ม "ให้โรโบเริ่มเดิน" ได้เลยครับ พยายามเก็บอัญมณีให้ครบทุกเม็ดนะ สู้ๆ!';
  }

  if (q.includes('สวัสดี') || q.includes('ดีครับ') || q.includes('ดีค่ะ') || q.includes('hello') || q.includes('hi')) {
    return '👋 สวัสดีครับคนเก่ง! พี่โรโบยินดีต้อนรับสู่โลกอัลกอริทึมครับ วันนี้อยากเล่นเกมไหน หรือมีคำถามเรื่องขั้นตอนการคิด ถามพี่โรโบได้เลยนะ!';
  }

  // คำตอบทั่วไปที่เป็นกำลังใจและอธิบายหัวใจหลัก
  return '🤖 ยอดเยี่ยมมากครับที่สงสัย! หัวใจของการเขียนโปรแกรมคือ "การคิดเป็นลำดับขั้นตอนทีละสเต็ป" (1-2-3)\n\nถ้าเข้าใจเป้าหมาย แล้วลองแบ่งปัญหาเป็นข้อย่อยๆ น้องๆ จะแก้ปัญหาได้ทุกเรื่องเลยครับ ลองถามพี่โรโบเกี่ยวกับ อัลกอริทึม, ลูป (Loop), บั๊ก (Bug) หรือการแยกย่อยปัญหา ได้อีกนะ!';
}
